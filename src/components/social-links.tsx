type Values = {
  discord_id?: string | null;
  steam_id?: string | null;
  twitch?: string | null;
  instagram?: string | null;
};

const ORDER: { key: Social["key"]; field: keyof Values }[] = [
  { key: "discord", field: "discord_id" },
  { key: "steam", field: "steam_id" },
  { key: "twitch", field: "twitch" },
  { key: "instagram", field: "instagram" },
];

/** Riga di icone social del profilo, coi colori ufficiali. */
export function SocialLinks({ values }: { values: Values }) {
  const items = ORDER.map(({ key, field }) => ({ key, value: values[field] }))
    .filter((i) => i.value && String(i.value).trim().length > 0);

  if (items.length === 0) return null;

  return (
    <>
      {/* gradiente Instagram, definito una volta */}
      <svg width="0" height="0" className="absolute" aria-hidden>
        <defs>
          <linearGradient id="instagram-gradient" x1="0%" y1="100%" x2="100%" y2="0%">
            <stop offset="0%" stopColor="#FEDA75" />
            <stop offset="25%" stopColor="#FA7E1E" />
            <stop offset="50%" stopColor="#D62976" />
            <stop offset="75%" stopColor="#962FBF" />
            <stop offset="100%" stopColor="#4F5BD5" />
          </linearGradient>
        </defs>
      </svg>
      <div className="flex flex-wrap items-center gap-2.5">
        {items.map(({ key, value }) => {
          const s = SOCIALS[key];
          const href = s.toHref(String(value));
          return (
            <a
              key={key}
              href={href}
              target="_blank"
              rel="noopener noreferrer"
              title={s.label}
              aria-label={s.label}
              className="group flex h-10 w-10 items-center justify-center rounded-xl border border-[var(--color-border)] bg-[var(--color-bg-elev-2)] hover:border-[var(--color-border-strong)] hover:-translate-y-0.5 transition-all"
            >
              <svg
                viewBox="0 0 24 24"
                className="h-[18px] w-[18px] transition-transform group-hover:scale-110"
                fill={s.gradient ? `url(#${s.gradient})` : s.color}
                aria-hidden
              >
                <path d={s.path} />
              </svg>
            </a>
          );
        })}
      </div>
    </>
  );
}
